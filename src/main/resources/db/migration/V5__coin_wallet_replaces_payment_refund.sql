-- Deposits are paid in coins (1 coin = 1.000 VND); coins are bought by bank transfer (QR) and never refunded as cash.
-- Booking payment intents, transactions and refunds are replaced by coin wallets and a coin ledger.
DROP TABLE sporthub.refund_requests;
DROP TABLE sporthub.payment_transactions;
DROP TABLE sporthub.payment_intents;

-- No booking rows exist before Sprint 3, so the NOT NULL column needs no backfill.
ALTER TABLE sporthub.bookings ADD COLUMN deposit_coins bigint NOT NULL;
ALTER TABLE sporthub.bookings ADD CONSTRAINT ck_bookings_deposit_coins
    CHECK (deposit_coins > 0 AND deposit_amount = deposit_coins * 1000);
-- Paying in coins confirms a booking at creation; HELD is no longer a starting state.
ALTER TABLE sporthub.bookings ALTER COLUMN status SET DEFAULT 'CONFIRMED';
ALTER TABLE sporthub.bookings ADD CONSTRAINT ck_bookings_lifecycle_timestamps CHECK (
    (status NOT IN ('CONFIRMED', 'COMPLETED') OR confirmed_at IS NOT NULL)
    AND (status <> 'COMPLETED' OR completed_at IS NOT NULL)
);

-- One wallet per user (customer) or per shop (receives deposits of completed bookings).
CREATE TABLE sporthub.coin_wallets (
    id uuid PRIMARY KEY,
    user_id uuid,
    shop_id uuid,
    balance bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_coin_wallets_user UNIQUE (user_id),
    CONSTRAINT uq_coin_wallets_shop UNIQUE (shop_id),
    CONSTRAINT fk_coin_wallets_user FOREIGN KEY (user_id) REFERENCES sporthub.users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_coin_wallets_shop FOREIGN KEY (shop_id) REFERENCES sporthub.shops (id) ON DELETE RESTRICT,
    CONSTRAINT ck_coin_wallets_owner CHECK ((user_id IS NULL) <> (shop_id IS NULL)),
    CONSTRAINT ck_coin_wallets_balance CHECK (balance >= 0)
);

-- A top-up order: the customer transfers amount_vnd with transfer_code as the transfer content.
CREATE TABLE sporthub.coin_top_ups (
    id uuid PRIMARY KEY,
    wallet_id uuid NOT NULL,
    transfer_code varchar(30) NOT NULL,
    coin_amount bigint NOT NULL,
    amount_vnd numeric(12,2) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'PENDING',
    provider_code varchar(50) NOT NULL,
    provider_transaction_id varchar(160),
    webhook_event_id uuid,
    expires_at timestamptz NOT NULL,
    paid_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_coin_top_ups_transfer_code UNIQUE (transfer_code),
    CONSTRAINT fk_coin_top_ups_wallet FOREIGN KEY (wallet_id) REFERENCES sporthub.coin_wallets (id) ON DELETE RESTRICT,
    CONSTRAINT fk_coin_top_ups_webhook FOREIGN KEY (webhook_event_id) REFERENCES sporthub.payment_webhook_events (id) ON DELETE RESTRICT,
    CONSTRAINT ck_coin_top_ups_amount CHECK (coin_amount > 0 AND amount_vnd = coin_amount * 1000),
    CONSTRAINT ck_coin_top_ups_status CHECK (status IN ('PENDING', 'PAID', 'EXPIRED')),
    CONSTRAINT ck_coin_top_ups_paid CHECK (
        (status = 'PAID' AND paid_at IS NOT NULL AND provider_transaction_id IS NOT NULL)
        OR (status <> 'PAID' AND paid_at IS NULL)
    )
);

CREATE UNIQUE INDEX uq_coin_top_ups_provider_tx
    ON sporthub.coin_top_ups (provider_code, provider_transaction_id) WHERE provider_transaction_id IS NOT NULL;
CREATE INDEX ix_coin_top_ups_wallet_created ON sporthub.coin_top_ups (wallet_id, created_at DESC);
CREATE INDEX ix_coin_top_ups_status_expires ON sporthub.coin_top_ups (status, expires_at);
CREATE INDEX ix_coin_top_ups_webhook ON sporthub.coin_top_ups (webhook_event_id);

-- Append-only ledger; every balance change writes exactly one entry. Unique indexes make credits idempotent.
CREATE TABLE sporthub.coin_ledger_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id uuid NOT NULL,
    entry_type varchar(30) NOT NULL,
    amount bigint NOT NULL,
    balance_after bigint NOT NULL,
    top_up_id uuid,
    booking_id uuid,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_coin_ledger_entries_wallet FOREIGN KEY (wallet_id) REFERENCES sporthub.coin_wallets (id) ON DELETE RESTRICT,
    CONSTRAINT fk_coin_ledger_entries_top_up FOREIGN KEY (top_up_id) REFERENCES sporthub.coin_top_ups (id) ON DELETE RESTRICT,
    CONSTRAINT fk_coin_ledger_entries_booking FOREIGN KEY (booking_id) REFERENCES sporthub.bookings (id) ON DELETE RESTRICT,
    CONSTRAINT ck_coin_ledger_entries_balance_after CHECK (balance_after >= 0),
    CONSTRAINT ck_coin_ledger_entries_type CHECK (
        (entry_type = 'TOP_UP' AND amount > 0 AND top_up_id IS NOT NULL AND booking_id IS NULL)
        OR (entry_type = 'BOOKING_DEPOSIT' AND amount < 0 AND booking_id IS NOT NULL AND top_up_id IS NULL)
        OR (entry_type IN ('BOOKING_DEPOSIT_RETURN', 'BOOKING_PAYOUT') AND amount > 0 AND booking_id IS NOT NULL AND top_up_id IS NULL)
    )
);

CREATE UNIQUE INDEX uq_coin_ledger_entries_top_up ON sporthub.coin_ledger_entries (top_up_id) WHERE top_up_id IS NOT NULL;
CREATE UNIQUE INDEX uq_coin_ledger_entries_booking_type
    ON sporthub.coin_ledger_entries (booking_id, entry_type) WHERE booking_id IS NOT NULL;
CREATE INDEX ix_coin_ledger_entries_wallet_created ON sporthub.coin_ledger_entries (wallet_id, created_at DESC);
